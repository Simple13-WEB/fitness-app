import type { Exercise } from '../types'
import rawDb from './free-exercise-db.json'

const dbMap = new Map<string, { images?: string[] }>(rawDb.map((e: any) => [e.id, e]))
const CARDIO_MAP: Record<string, string> = {
  'cardio-run': 'Jogging_Treadmill',
  'cardio-stairs': 'Stairmaster',
  'cardio-swim': 'Rowing_Stationary',
  'cardio-rope': 'Rope_Jumping',
}

function getImageUrl(exerciseId: string, frame: number = 0): string | undefined {
  const dbId = CARDIO_MAP[exerciseId] || exerciseId.replace(/^ex-/, '')
  const entry = dbMap.get(dbId)
  if (!entry?.images?.[frame]) return undefined
  return `https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/${entry.images[frame]}`
}

